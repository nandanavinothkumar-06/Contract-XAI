"""
Candidate Finding Schema and Provenance Contracts for CONTRACTRISK-XAI.

Defines standardized data models for candidate model findings generated by
contract risk analysis models. Enforces strict provenance, explicit confidence
semantics, document version consistency, and deduplication keys without
label leakage, fabricated text, or unauthorized client disclosure.
"""

from enum import Enum
from typing import List, Dict, Any, Optional
from datetime import datetime, timezone
from pydantic import BaseModel, Field, ConfigDict


class ConfidenceSemantics(str, Enum):
    """
    Explicit mathematical and operational interpretation of the model's confidence value.
    Different semantics must NEVER be treated as interchangeable.
    """
    MULTILABEL_SIGMOID_SCORE = "MULTILABEL_SIGMOID_SCORE"
    MULTICLASS_SOFTMAX_SCORE = "MULTICLASS_SOFTMAX_SCORE"
    RAW_LOGIT = "RAW_LOGIT"
    HEURISTIC_SCORE = "HEURISTIC_SCORE"
    UNSPECIFIED = "UNSPECIFIED"


class CandidateOrigin(str, Enum):
    """Provenance origin of the candidate finding."""
    MODEL_INFERENCE_BATCH = "MODEL_INFERENCE_BATCH"
    SYNTHETIC_TEST_FIXTURE = "SYNTHETIC_TEST_FIXTURE"
    LAWYER_CREATED = "LAWYER_CREATED"
    DEMO_SEED = "DEMO_SEED"


class VersionConsistencyStatus(str, Enum):
    """Consistency of the candidate finding against the active document revision."""
    CONSISTENT = "CONSISTENT"
    STALE = "STALE"
    UNKNOWN = "UNKNOWN"


class LabelMappingStatus(str, Enum):
    """
    Status of mapping from the model's raw output label to an Indian commercial risk category.
    If no verified mapping exists, UNSUPPORTED_LABEL_MAPPING must be reported rather than inventing one.
    """
    MAPPED = "MAPPED"
    UNSUPPORTED_LABEL_MAPPING = "UNSUPPORTED_LABEL_MAPPING"
    EXACT_MATCH = "EXACT_MATCH"


class CandidateFindingRecord(BaseModel):
    """
    Standardized experimental record representing a single model-generated candidate finding.
    Binds the candidate assertion to its source clause, model provenance, retrieval evidence,
    and temporal document version.
    """
    model_config = ConfigDict(extra="forbid")

    candidate_finding_id: str = Field(
        ...,
        description="Deterministic unique identifier (e.g. SHA-256 digest or UUID) for this candidate finding."
    )
    contract_id: str = Field(
        ...,
        description="Unique identifier of the source contract document."
    )
    contract_version: int = Field(
        ...,
        ge=1,
        description="Monotonically increasing version integer of the contract snapshot at evaluation time."
    )
    document_content_hash: str = Field(
        ...,
        description="Cryptographic SHA-256 digest of the source contract text snapshot."
    )
    clause_id: str = Field(
        ...,
        description="Identifier of the specific clause segment within the contract."
    )
    clause_text: str = Field(
        ...,
        description="Verbatim text of the segmented clause."
    )
    prediction_category: str = Field(
        ...,
        description="Target legal risk category (e.g. INDEMNIFICATION) or documented unmapped raw label."
    )
    raw_model_label: str = Field(
        ...,
        description="Verbatim class label or index emitted by the underlying model checkpoint."
    )
    candidate_finding_text: Optional[str] = Field(
        default=None,
        description="Explanatory finding assertion text ONLY when generated by an authentic model; never fabricated."
    )
    model_id: str = Field(
        ...,
        description="Identifier of the model architecture and checkpoint (e.g. nlpaueb/legal-bert-base-uncased)."
    )
    model_version: str = Field(
        ...,
        description="Version string, commit SHA, or checkpoint path of the model artifact."
    )
    model_task: str = Field(
        ...,
        description="Operational task type (e.g. CLASSIFICATION_MULTILABEL, CLASSIFICATION_MULTICLASS)."
    )
    confidence_value: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Continuous numerical confidence score emitted by the model."
    )
    confidence_semantics: ConfidenceSemantics = Field(
        ...,
        description="Explicit mathematical semantics of confidence_value. Never assume calibrated probability."
    )
    confidence_is_calibrated: bool = Field(
        default=False,
        description="Whether confidence_value has undergone empirical temperature/isotonic calibration."
    )
    prediction_timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="UTC ISO-8601 timestamp of inference execution."
    )
    source_document_provenance: Dict[str, Any] = Field(
        default_factory=dict,
        description="Metadata capturing document filename, extraction method, page count, and tenant context."
    )
    evidence_quality_status: Optional[str] = Field(
        default=None,
        description="Evidence quality status from statutory retrieval (e.g. TRACEABLE, PARTIAL, INSUFFICIENT)."
    )
    retrieved_passages: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="List of statutory passages retrieved by BM25/lexical search for this clause."
    )
    version_consistency_status: VersionConsistencyStatus = Field(
        default=VersionConsistencyStatus.UNKNOWN,
        description="Whether the finding was generated on the active document revision or a superseded draft."
    )
    label_mapping_status: LabelMappingStatus = Field(
        default=LabelMappingStatus.MAPPED,
        description="Status of mapping the raw model label into an Indian commercial risk category."
    )
    missing_capabilities: List[str] = Field(
        default_factory=list,
        description="Explicitly recorded capability blockers or missing metadata (e.g. NO_CALIBRATION_CURVE)."
    )
    origin: CandidateOrigin = Field(
        default=CandidateOrigin.MODEL_INFERENCE_BATCH,
        description="Origin of this finding record to prevent mixing lawyer or seed data into model evaluations."
    )
    is_synthetic_fixture: bool = Field(
        default=False,
        description="Explicitly marks whether this candidate is a synthetic software test fixture."
    )
    is_disclosed_to_client: bool = Field(
        default=False,
        description="STRICT INVARIANT: Generated candidates MUST NOT automatically be disclosed to clients."
    )


class DuplicateFindingEntry(BaseModel):
    """Audit log entry capturing duplicate findings collapsed during ingestion."""
    canonical_finding_id: str
    duplicate_finding_id: str
    deduplication_key: str
    contract_id: str
    clause_id: str
    prediction_category: str
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
