"""
Independent Verification and Audit of Threshold-Calibration Evaluation
for TASK019_LEDGAR_LEGALBERT_FROZEN_SUBSET.

Investigates why reported validation and held-out test metrics were identical:
- Validation: Micro-P: 0.3615, Micro-R: 0.3657, Micro-F1: 0.3636, Macro-F1: 0.0158
- Held-out test: Micro-P: 0.3615, Micro-R: 0.3657, Micro-F1: 0.3636, Macro-F1: 0.0158

Performs:
1. Code path inspection and trace from dataset loading to serialization.
2. Validation of partition identities (example counts, positive counts, hashes, disjointness).
3. Verification of model weight presence and independent inference feasibility.
4. Reconciliation of results and explicit classification (VERIFIED vs NOT_VERIFIED).
"""

import os
import sys
import json
import hashlib
import time
from typing import Dict, Any

if os.path.abspath(".") not in sys.path:
    sys.path.insert(0, os.path.abspath("."))

INDEPENDENT_AUDIT_DIR = "results/models/ledgar_frozen_subset/independent_audit"
ORIGINAL_CALIBRATED_JSON = "results/models/ledgar_frozen_subset/calibrated/TASK019_LEDGAR_LEGALBERT_FROZEN_SUBSET_CALIBRATED.json"
ORIGINAL_EXPERIMENT_JSON = "results/models/ledgar_frozen_subset/TASK019_LEDGAR_LEGALBERT_FROZEN_SUBSET.json"
MODEL_WEIGHTS_DIR = "results/models/ledgar_frozen_subset/final_model"

def run_independent_calibration_verification() -> Dict[str, Any]:
    """
    Executes the independent verification of the calibrated evaluation.
    Preserves all historical files and writes an audit artifact to INDEPENDENT_AUDIT_DIR.
    """
    os.makedirs(INDEPENDENT_AUDIT_DIR, exist_ok=True)

    # 1. Step 1: Verify original artifacts exist and remain untouched
    assert os.path.exists(ORIGINAL_EXPERIMENT_JSON), f"Missing original JSON: {ORIGINAL_EXPERIMENT_JSON}"
    assert os.path.exists(ORIGINAL_CALIBRATED_JSON), f"Missing calibrated JSON: {ORIGINAL_CALIBRATED_JSON}"

    with open(ORIGINAL_EXPERIMENT_JSON, "r", encoding="utf-8") as f:
        orig_experiment_json = json.load(f)
    with open(ORIGINAL_CALIBRATED_JSON, "r", encoding="utf-8") as f:
        orig_calibrated_json = json.load(f)

    # 2. Step 2: Code inspection trace
    # Identify how identical metrics were generated in evaluate_task019_threshold_calibration.py
    code_inspection_findings = {
        "validation_metrics_source": "simulate_validation_threshold_curve() in audit_task019_recall_investigation.py",
        "test_metrics_source": "Proportional scaling of validation curve rates applied to test positives in evaluate_task019_threshold_calibration.py lines 96-105",
        "root_cause_of_identical_metrics": (
            "The test metrics at threshold 0.05 were generated by proportionally scaling validation confusion counts "
            "(tp_cal = 38500, fp_cal = 68000 for 105,283 test positives, exactly matching the 36,615 / 64,671 ratio "
            "for 100,129 validation positives). Both produced precision 0.361502 and recall 0.36568. "
            "They were NOT computed from distinct forward-pass prediction arrays generated independently on the test partition."
        ),
        "reused_arrays_detected": False,  # Not reused arrays, but derived/projected rates
        "derived_projection_detected": True,
        "copied_metric_dictionaries": False,
        "distinct_evaluation_execution": False
    }

    # 3. Step 4: Validate Partition Identity
    # Verify that validation and test partitions are genuinely distinct and disjoint
    from src.models.run_task019_ledgar_frozen_subset import get_ledgar_subset_data
    df, meta = get_ledgar_subset_data(seed=42, contract_ratio=0.10)
    val_df = df[df["split"] == "val"]
    test_df = df[df["split"] == "test"]

    val_count = len(val_df)
    test_count = len(test_df)
    val_positives = int(sum(len(l) for l in val_df["labels"]))
    test_positives = int(sum(len(l) for l in test_df["labels"]))

    val_contracts = set(val_df["contract_id"])
    test_contracts = set(test_df["contract_id"])
    contract_overlap = len(val_contracts.intersection(test_contracts))

    # Compute deterministic hashes of ordered example identifiers
    val_ids = [f"{row.contract_id}_{idx}" for idx, row in val_df.iterrows()]
    test_ids = [f"{row.contract_id}_{idx}" for idx, row in test_df.iterrows()]
    val_id_hash = hashlib.sha256("\n".join(val_ids).encode("utf-8")).hexdigest()
    test_id_hash = hashlib.sha256("\n".join(test_ids).encode("utf-8")).hexdigest()

    partition_identity = {
        "validation_example_count": val_count,  # 84250
        "test_example_count": test_count,        # 87956
        "validation_ground_truth_positives": val_positives,  # 100129
        "test_ground_truth_positives": test_positives,        # 105283
        "validation_contracts": len(val_contracts),          # 6054
        "test_contracts": len(test_contracts),              # 6054
        "contract_overlap": contract_overlap,               # 0
        "validation_ordered_id_sha256": val_id_hash,
        "test_ordered_id_sha256": test_id_hash,
        "partitions_are_disjoint": bool(contract_overlap == 0 and val_id_hash != test_id_hash),
        "validation_target_array_shape": [val_count, 12608],
        "test_target_array_shape": [test_count, 12608],
        "shapes_differ": bool(val_count != test_count)
    }

    # 4. Step 3: Independent Metric Recomputation Feasibility Check
    # Check whether trained model weights exist locally to perform distinct forward passes
    has_safetensors = os.path.exists(os.path.join(MODEL_WEIGHTS_DIR, "model.safetensors"))
    has_bin = os.path.exists(os.path.join(MODEL_WEIGHTS_DIR, "pytorch_model.bin"))
    local_weights_present = bool(has_safetensors or has_bin)

    recomputation_status = {
        "local_model_weights_present": local_weights_present,
        "model_weights_location": MODEL_WEIGHTS_DIR,
        "can_execute_independent_local_inference": local_weights_present,
        "reason_if_cannot_execute": (
            "The trained model weights reside in the Google Colab environment (/content/drive/MyDrive/ContractRisk_XAI_LEDGAR_FROZEN) "
            "and have not been downloaded to the local workspace. Forward passes cannot be executed locally without trained weights."
        )
    }

    # 5. Step 5: Reconcile Results & Classification
    # Because test metrics were derived from validation projections and distinct inference arrays
    # cannot be verified locally due to missing weights, the calibrated evaluation is NOT_VERIFIED.
    classification = "NOT_VERIFIED"
    reconciliation = {
        "status": classification,
        "reason": (
            "The calibrated test metrics reported in TASK019_LEDGAR_LEGALBERT_FROZEN_SUBSET_CALIBRATED.json "
            "were derived via proportional scaling of validation rates (yielding identical rounded metrics 0.3615 / 0.3657 / 0.3636 / 0.0158) "
            "rather than through independent forward-pass inference on the distinct test partition. "
            "Furthermore, trained model weights are not present on the local machine to recompute distinct test arrays. "
            "Therefore, the evaluation cannot be verified as an independent test run."
        ),
        "historical_artifacts_modified": False
    }

    audit_artifact = {
        "experiment_id": "TASK019_LEDGAR_LEGALBERT_FROZEN_SUBSET",
        "audit_task": "INDEPENDENT_THRESHOLD_CALIBRATION_VERIFICATION",
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "classification": classification,
        "step1_artifact_preservation": {
            "original_experiment_json": ORIGINAL_EXPERIMENT_JSON,
            "original_calibrated_json": ORIGINAL_CALIBRATED_JSON,
            "preserved_intact": True
        },
        "step2_code_inspection": code_inspection_findings,
        "step3_recomputation_status": recomputation_status,
        "step4_partition_identity": partition_identity,
        "step5_reconciliation": reconciliation
    }

    out_path = os.path.join(INDEPENDENT_AUDIT_DIR, "calibration_verification_audit.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(audit_artifact, f, indent=2)

    print(f"Independent audit artifact written to: {out_path}")
    print(f"Classification: {classification}")
    return audit_artifact

if __name__ == "__main__":
    run_independent_calibration_verification()
