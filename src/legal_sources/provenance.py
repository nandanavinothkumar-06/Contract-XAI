def is_retrieval_eligible(status: VerificationStatus) -> bool:
    """
    Returns True if a source's verification status permits inclusion in candidate retrieval.
    Rejects completely unverified, failed, or repository-only unvalidated files.
    """
    eligible = {
        VerificationStatus.VERIFIED_OFFICIAL,
        VerificationStatus.VERIFIED_AUTHORITATIVE,
        VerificationStatus.CONTENT_MATCH_VERIFIED,
        VerificationStatus.CURRENTNESS_VERIFIED,
        VerificationStatus.PARTIALLY_VERIFIED,
        VerificationStatus.OFFICIAL_SOURCE_IDENTIFIED,
    }
    return status in eligible

def is_authoritatively_verified(status: VerificationStatus) -> bool:
    """
    Returns True ONLY if a source's text has been actively verified against an official artifact.
    A stable local checksum or URL in metadata is NOT sufficient.
    """
    authoritative = {
        VerificationStatus.CONTENT_MATCH_VERIFIED,
        VerificationStatus.CURRENTNESS_VERIFIED,
    }
    return status in authoritative

